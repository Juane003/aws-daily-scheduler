/**
 * Generates a PostgreSQL seed for `registries` as a COPY ... FROM STDIN (CSV) script.
 *
 *   npm run seed:generate -- --rows 1000 --providers 50 --hot-provider 0.2 \
 *     --out database/seeds/registries.generated.sql
 *   psql "$DATABASE_URL" -f database/seeds/registries.generated.sql
 *
 * Reference implementation: not run against Aurora.
 */
import { createWriteStream } from 'node:fs';
import { once } from 'node:events';
import { parseArgs } from 'node:util';
import type { Writable } from 'node:stream';
import { generateRegistries, type RegistryRow } from '../src/simulation/registries.js';

const { values } = parseArgs({
  options: {
    rows: { type: 'string', default: '1000' },
    providers: { type: 'string', default: '50' },
    'hot-provider': { type: 'string', default: '0' },
    seed: { type: 'string', default: '1' },
    out: { type: 'string' },
  },
});

const csvField = (value: string): string => `"${value.replaceAll('"', '""')}"`;

const toCsvLine = (r: RegistryRow): string =>
  [
    r.id,
    csvField(r.providerId),
    csvField(r.endpoint),
    r.httpMethod,
    csvField(JSON.stringify(r.body)),
    r.slot,
    r.enabled,
  ]
    .map(String)
    .join(',');

async function write(out: Writable, chunk: string): Promise<void> {
  if (!out.write(chunk)) await once(out, 'drain');
}

const out: Writable = values.out === undefined ? process.stdout : createWriteStream(values.out);

await write(out, '-- Generated by scripts/generate-seeds.ts. Do not edit by hand.\n');
await write(out, 'BEGIN;\n');
await write(
  out,
  'COPY registries (id, provider_id, endpoint, http_method, body, slot, enabled) FROM STDIN WITH (FORMAT csv);\n',
);
for (const row of generateRegistries({
  rows: Number(values.rows),
  providers: Number(values.providers),
  hotProviderShare: Number(values['hot-provider']),
  seed: Number(values.seed),
})) {
  await write(out, `${toCsvLine(row)}\n`);
}
await write(out, '\\.\nCOMMIT;\n');
if (out !== process.stdout) out.end();
